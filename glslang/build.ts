// Builds glslang's front end, with src/driver.cpp, into a WebAssembly module:
// build/glslang.wasm, and build/glslang-wasm.ts with it as base64, which
// glslang.ts loads.
//
// The source is the pinned release, cloned once into node_modules/.cache and
// checked against its commit. Each file is compiled by itself, in parallel,
// and Zig's cache makes a rebuild of unchanged files nearly free.

import { execFile } from "node:child_process";
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { availableParallelism } from "node:os";
import { basename, join } from "node:path";
import { promisify } from "node:util";
import { ensureZig } from "@moreplease/zig";

const GLSLANG = {
  version: "16.6.0",
  commit: "e1b562a8bed273a02f30b59b66a5d499793cede5",
  url: "https://github.com/KhronosGroup/glslang.git",
};

const run = promisify(execFile);
const root = import.meta.dirname;
const source = join(
  root,
  "node_modules",
  ".cache",
  `glslang-${GLSLANG.version}`,
);
const build = join(root, "build");

async function head(): Promise<string | undefined> {
  try {
    const { stdout } = await run("git", ["-C", source, "rev-parse", "HEAD"]);
    return stdout.trim();
  } catch {
    return undefined;
  }
}

async function fetchSource(): Promise<void> {
  if ((await head()) === GLSLANG.commit) {
    return;
  }
  rmSync(source, { recursive: true, force: true });
  await run("git", [
    "-c",
    "advice.detachedHead=false",
    "clone",
    "--quiet",
    "--depth=1",
    `--branch=${GLSLANG.version}`,
    GLSLANG.url,
    source,
  ]);
  const commit = await head();
  if (commit !== GLSLANG.commit) {
    throw new Error(
      `glslang ${GLSLANG.version} is commit ${commit}, expected ${GLSLANG.commit}`,
    );
  }
}

// What glslang's CMake build generates from build_info.h.tmpl.
function writeBuildInfo(): void {
  const [major, minor, patch] = GLSLANG.version.split(".");
  const template = readFileSync(join(source, "build_info.h.tmpl"), "utf8");
  const dir = join(build, "include", "glslang");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "build_info.h"),
    template
      .replace("@major@", major!)
      .replace("@minor@", minor!)
      .replace("@patch@", patch!)
      .replace("@flavor@", ""),
  );
}

function sources(): string[] {
  const cpp = (dir: string) =>
    readdirSync(join(source, dir))
      .filter((f) => f.endsWith(".cpp"))
      .map((f) => join(source, dir, f));
  return [
    ...cpp("glslang/MachineIndependent"),
    ...cpp("glslang/MachineIndependent/preprocessor"),
    ...cpp("glslang/GenericCodeGen"),
    join(source, "glslang/ResourceLimits/ResourceLimits.cpp"),
    join(root, "src/os.cpp"),
    join(root, "src/driver.cpp"),
  ];
}

async function compile(zig: string): Promise<void> {
  const target = ["-target", "wasm32-wasi", "-mexec-model=reactor"];
  const flags = [
    ...target,
    "-Os",
    "-std=c++17",
    "-fno-exceptions",
    "-fno-rtti",
    "-DNDEBUG",
    `-I${source}`,
    `-I${join(source, "glslang", "Include")}`,
    `-I${join(build, "include")}`,
    "-include",
    join(root, "src", "single-threaded.h"),
  ];
  const objects = join(build, "obj");
  mkdirSync(objects, { recursive: true });
  const files = sources();
  const outputs = files.map((file, i) =>
    join(objects, `${i}-${basename(file, ".cpp")}.o`),
  );
  let next = 0;
  const worker = async () => {
    while (next < files.length) {
      const i = next++;
      await run(zig, ["c++", ...flags, "-c", files[i]!, "-o", outputs[i]!]);
    }
  };
  await Promise.all(
    Array.from(
      { length: Math.min(availableParallelism(), files.length) },
      worker,
    ),
  );
  await run(zig, [
    "c++",
    ...target,
    "-Os",
    "-s",
    ...outputs,
    "-o",
    join(build, "glslang.wasm"),
  ]);
}

function writeModule(): void {
  const wasm = readFileSync(join(build, "glslang.wasm"));
  writeFileSync(
    join(build, "glslang-wasm.ts"),
    [
      "// Generated by build.ts.",
      `export const version = ${JSON.stringify(GLSLANG.version)};`,
      `export const wasm = ${JSON.stringify(wasm.toString("base64"))};`,
      "",
    ].join("\n"),
  );
}

const started = performance.now();
const zig = await ensureZig();
await fetchSource();
writeBuildInfo();
await compile(zig);
writeModule();
const size = readFileSync(join(build, "glslang.wasm")).length;
console.log(
  `glslang ${GLSLANG.version}: build/glslang.wasm, ${(size / 1e6).toFixed(2)} MB, in ${((performance.now() - started) / 1000).toFixed(1)} s`,
);
